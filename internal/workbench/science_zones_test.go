// N8 (round 2): Chrome's Intl names some zones by older CLDR names (an
// override of Asia/Kolkata reads back as Asia/Calcutta, Europe/Kyiv as
// Europe/Kiev). Two names of one zone are the same identity; a different
// zone is still refused.
func TestScienceZoneNamesOfOneZoneAgree(t *testing.T) {
	now := time.Now()
	for _, pair := range [][2]string{{"Asia/Kolkata", "Asia/Calcutta"}, {"Europe/Kyiv", "Europe/Kiev"}} {
		guest := testScienceIdentity
		guest.Timezone = pair[0]
		reports := goodProbeReports(guest)
		for i := range reports {
			reports[i].Timezone = pair[1]
		}
		if reason := checkScienceProbe(guest, reports, now); reason != "" {
			t.Errorf("%s read back as %s: refused (%s)", pair[0], pair[1], reason)
		}
		// The guest browser's own answer, as the environment was set.
		audit := scienceGuestAudit{Timezone: pair[1], ExpectedTimezone: pair[0], Language: "fr-FR", Languages: []string{"fr-FR"}, Platform: "Linux x86_64"}
		audit.Device = &struct {
			UserAgent   string `json:"user_agent"`
			Platform    string `json:"platform"`
			ClientHints *struct {
				Brands   []scienceUABrand `json:"brands"`
				Platform string           `json:"platform"`
				Mobile   bool             `json:"mobile"`
			} `json:"client_hints"`
		}{UserAgent: "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/157.0.0.0 Safari/537.36"}
		if _, err := identityFromGuestAudit(audit, pair[0], "fr-FR"); err != nil {
			t.Errorf("guest browser on %s reporting %s: %v", pair[0], pair[1], err)
		}
		// A host on the other name of the guest's zone shows nothing apart.
		offset, _ := jsOffset(pair[0], now)
		if distinct := newScienceAudit(scienceHostIdentity{Timezone: pair[1], Offset: &offset, Languages: guest.Languages}, guest, now).Distinct; distinct.Timezone {
			t.Errorf("host %s and guest %s counted as different zones", pair[1], pair[0])
		}
	}
	// A different zone with today's offset is still a different zone.
	guest := testScienceIdentity
	guest.Timezone = "Asia/Kolkata"
	reports := goodProbeReports(guest)
	for i := range reports {
		reports[i].Timezone = "Asia/Colombo"
	}
	if reason := checkScienceProbe(guest, reports, now); reason == "" {
		t.Error("Asia/Colombo accepted for Asia/Kolkata")
	}
	// The audit looks for every name of the host's zone.
	offset := 480
	audit := newScienceAudit(scienceHostIdentity{Timezone: "Europe/Kiev", Offset: &offset, Languages: []string{"uk-UA"}}, guest, now)
	target, _ := url.Parse("/api/echo")
	if category := auditRequest(audit, target, http.Header{}, []byte(`{"tz":"Europe/Kyiv"}`)); category == "" {
		t.Error("the host zone's other name passed the audit")
	}
}

// TestScienceBrowserZoneNames pins scienceChromeZone to what Chrome's Intl
// reports for every zone name in Go's tzdata. CAGE_UPDATE_ZONES=1 rewrites
// science_zones.go from the browser under test.
func TestScienceBrowserZoneNames(t *testing.T) {
	archive, err := zip.OpenReader(filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		t.Skip("no Go tzdata archive:", err)
	}
	var names []string
	for _, entry := range archive.File {
		if !strings.HasSuffix(entry.Name, "/") && scienceZoneName.MatchString(entry.Name) {
			names = append(names, entry.Name)
		}
	}
	archive.Close()
	browser := launchTestBrowser(t, nil)
	session := browser.page(t)
	list, _ := json.Marshal(names)
	var result struct {
		Result struct {
			Value string `json:"value"`
		} `json:"result"`
	}
	expression := `(() => { const out = {}; for (const name of ` + string(list) + `) { try { out[name] = new Intl.DateTimeFormat("en", { timeZone: name }).resolvedOptions().timeZone } catch { out[name] = "" } } return JSON.stringify(out) })()`
	if err := browser.call(session, "Runtime.evaluate", map[string]any{"expression": expression, "returnByValue": true}, &result); err != nil {
		t.Fatal(err)
	}
	var chrome map[string]string
	if err := json.Unmarshal([]byte(result.Result.Value), &chrome); err != nil {
		t.Fatal(err)
	}
	want := map[string]string{}
	for name, reported := range chrome {
		if reported != "" && reported != name {
			want[name] = reported
		}
	}
	if os.Getenv("CAGE_UPDATE_ZONES") == "1" {
		var version string
		var info struct {
			Product string `json:"product"`
		}
		if browser.call("", "Browser.getVersion", map[string]any{}, &info) == nil {
			version = info.Product
		}
		keys := make([]string, 0, len(want))
		for name := range want {
			keys = append(keys, name)
		}
		slices.Sort(keys)
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by TestScienceBrowserZoneNames (CAGE_UPDATE_ZONES=1) from\n// %s's Intl and Go's tzdata (%s). DO NOT EDIT.\n\npackage workbench\n\n", version, runtime.Version())
		b.WriteString("// scienceChromeZone maps a zone name Go knows to the name Chrome's Intl\n// reports for it, where the two differ (round-2 N8).\nvar scienceChromeZone = map[string]string{\n")
		for _, name := range keys {
			fmt.Fprintf(&b, "\t%q: %q,\n", name, want[name])
		}
		b.WriteString("}\n")
		source, err := format.Source([]byte(b.String()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("science_zones.go", source, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d names (%s)", len(keys), version)
		return
	}
	for name, reported := range want {
		if scienceChromeZone[name] != reported {
			t.Errorf("Chrome reports %s as %s; scienceChromeZone has %q", name, reported, scienceChromeZone[name])
		}
	}
	for name, reported := range scienceChromeZone {
		if want[name] != reported {
			t.Errorf("scienceChromeZone has %s -> %s; Chrome reports %q", name, reported, chrome[name])
		}
	}
}
